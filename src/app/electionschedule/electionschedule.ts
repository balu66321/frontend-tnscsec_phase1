interface ScheduleStage {
  stageId: number | null;
  no: number;
  programme: string;
  statutoryRequirement: string;
  actualProgramme: string | null;
  permissibleCutoffDate: string | null;
  remarks: string | null;
  isAutoGenerated: boolean;
  isHolidayAdjusted: boolean;
}

interface EditSnapshot {
  actualProgramme: string | null;
  permissibleCutoffDate: string | null;
  remarks: string | null;
}

interface Holiday {
  id: number;
  date: string;
  description: string;
}

