@Component({
  selector: 'app-electionschedule',
  standalone: true,
  imports: [CommonModule, FormsModule, RouterLink],
  templateUrl: './electionschedule.html',
  styleUrls: ['./electionschedule.css']
})
export class ElectionSchedule implements OnInit {

  // Anyone can view this page; only an admin can edit the fields.
  isAdmin = localStorage.getItem('role') === 'admin';

  // Single section on this page — locked until the admin clicks Edit,
  // "Submit" saves and locks it back (same pattern as Election
  // Programme).
  unlocked = false;

  // id of the election_schedule row on the backend. null until the
  // first successful Generate — after that, Polling Date's Submit
  // calls "regenerate" instead of "generate".
  scheduleId: number | null = null;

  // The date of poll — shown above the table with its own Submit,
  // which generates/regenerates every row's dates on the backend
  // (holiday-aware; manually-edited rows survive a regenerate).
  pollingDate: string | null = null;

  items: ScheduleStage[] = CHECKLIST.map(c => ({
    stageId: null,
    no: c.no,
    programme: c.programme,
    statutoryRequirement: c.statutoryRequirement,
    actualProgramme: null,
    permissibleCutoffDate: null,
    remarks: null,
    isAutoGenerated: false,
    isHolidayAdjusted: false
  }));

  // Snapshot of each row's editable fields, taken when Edit is
  // clicked — Submit diffs against this to know which rows actually
  // changed, and PATCHes only those (by their real stage id).
  private editSnapshot = new Map<number, EditSnapshot>();

  // ==========================================
  // GOVERNMENT HOLIDAYS — feed the backend's skip logic
  // ==========================================
  holidays: Holiday[] = [];
  newHolidayDate: string | null = null;
  newHolidayDescription = '';

  constructor(private userService: UserService) { }

  ngOnInit(): void {
    this.userService.getElectionSchedules().subscribe({
      next: (res: any) => {
        const rows: any[] = Array.isArray(res?.data) ? res.data : (res?.data ? [res.data] : []);
        const record = rows.filter((r: any) => r.is_active !== 0)[0]; // newest first, per the API
        if (record) this.applyRecord(record);
      },
      error: () => {
        // No schedule generated yet (or endpoint unreachable) — page
        // just shows the blank reference checklist.
      }
    });

    this.loadHolidays();
  }

  loadHolidays(): void {
    this.userService.getElectionScheduleHolidays().subscribe({
      next: (res: any) => {
        const rows: any[] = Array.isArray(res?.data) ? res.data : [];
        this.holidays = rows
          .filter((h: any) => h.is_active !== 0)
          .map((h: any) => ({
            id: h.id,
            date: this.toDateInput(h.holiday_date) || '',
            description: h.description
          }))
          .sort((a, b) => a.date.localeCompare(b.date));
      },
      error: () => {
        // No holidays yet, or endpoint unreachable — list stays empty.
      }
    });
  }

  addHoliday(): void {
    if (!this.isAdmin) return;

    if (!this.newHolidayDate || !this.newHolidayDescription.trim()) {
      alert('தேதி மற்றும் விவரத்தை உள்ளிடவும்');
      return;
    }

    this.userService.addElectionScheduleHoliday({
      holiday_date: this.newHolidayDate,
      description: this.newHolidayDescription.trim()
    }).subscribe({
      next: () => {
        this.newHolidayDate = null;
        this.newHolidayDescription = '';
        this.loadHolidays();
        this.notifyRegenerateIfNeeded();
      },
      error: (err: any) => alert(err?.error?.message || 'Holiday add failed')
    });
  }

  removeHoliday(holiday: Holiday): void {
    if (!this.isAdmin) return;
    if (!confirm(`"${holiday.description}" (${holiday.date}) விடுமுறையை நீக்கவா?`)) return;

    this.userService.deleteElectionScheduleHoliday(holiday.id).subscribe({
      next: () => {
        this.loadHolidays();
        this.notifyRegenerateIfNeeded();
      },
      error: (err: any) => alert(err?.error?.message || 'Holiday remove failed')
    });
  }

  // Adding/removing a holiday only affects FUTURE generate/regenerate
  // calls — an already-generated schedule doesn't update itself.
  private notifyRegenerateIfNeeded(): void {
    if (this.scheduleId) {
      alert(
        'விடுமுறை பட்டியல் புதுப்பிக்கப்பட்டது. ஏற்கனவே உருவாக்கப்பட்ட அட்டவணையில் இது தானாக பிரதிபலிக்காது — ' +
        'மேலே உள்ள Submit (Date of Poll) பொத்தானை மீண்டும் அழுத்தி Regenerate செய்யவும்.'
      );
    }
  }

  private toDateInput(iso: string | null | undefined): string | null {
    return iso ? String(iso).slice(0, 10) : null;
  }

  private applyRecord(record: any): void {

    this.scheduleId = record.id;
    this.pollingDate = this.toDateInput(record.poll_date);

    const stages: any[] = Array.isArray(record.election_schedule_stage)
      ? [...record.election_schedule_stage].sort((a, b) => a.sl_no - b.sl_no)
      : [];

    if (stages.length > 0) {
      this.items = stages.map((s: any) => ({
        stageId: s.id,
        no: s.sl_no,
        programme: s.programme,
        statutoryRequirement: s.statutory_requirement,
        actualProgramme: this.toDateInput(s.actual_date),
        permissibleCutoffDate: this.toDateInput(s.permissible_cutoff_date),
        remarks: s.remarks ?? null,
        isAutoGenerated: !!s.is_auto_generated,
        isHolidayAdjusted: !!s.is_holiday_adjusted
      }));
    }
  }

  startEdit(): void {
    if (!this.isAdmin || !this.scheduleId) return;

    this.editSnapshot.clear();
    this.items.forEach(item => {
      if (item.stageId != null) {
        this.editSnapshot.set(item.stageId, {
          actualProgramme: item.actualProgramme,
          permissibleCutoffDate: item.permissibleCutoffDate,
          remarks: item.remarks
        });
      }
    });

    this.unlocked = true;
  }

  submit(): void {
    if (!this.isAdmin || !this.scheduleId) return;

    const requests: Observable<any>[] = [];

    for (const item of this.items) {
      if (item.stageId == null) continue;

      const before = this.editSnapshot.get(item.stageId);
      if (!before) continue;

      const changes: any = {};
      if (item.actualProgramme !== before.actualProgramme) changes.actual_date = item.actualProgramme;
      if (item.permissibleCutoffDate !== before.permissibleCutoffDate) changes.permissible_cutoff_date = item.permissibleCutoffDate;
      if (item.remarks !== before.remarks) changes.remarks = item.remarks;

      if (Object.keys(changes).length > 0) {
        requests.push(this.userService.updateElectionScheduleStage(item.stageId, changes));
      }
    }

    if (requests.length === 0) {
      this.unlocked = false;
      alert('மாற்றங்கள் இல்லை (No changes to save)');
      return;
    }

    forkJoin(requests).subscribe({
      next: () => {
        this.unlocked = false;
        alert('சமர்ப்பிக்கப்பட்டது (Submitted successfully)');

        // Re-fetch so is_auto_generated / is_holiday_adjusted flags
        // reflect what the backend actually recorded after the edit.
        this.userService.getElectionSchedule(this.scheduleId!).subscribe({
          next: (res: any) => { if (res?.data) this.applyRecord(res.data); }
        });
      },
      error: (err: any) => alert(err?.error?.message || 'Submit failed')
    });
  }

  // Polling Date's own Submit — generates a brand-new schedule the
  // first time, or regenerates the existing one (preserving
  // manually-edited rows) on every call after that.
  generateDates(): void {

    if (!this.isAdmin) return;

    if (!this.pollingDate) {
      alert('வாக்குப்பதிவு தேதியை முதலில் தேர்வு செய்யவும்');
      return;
    }

    const payload = { poll_date: this.pollingDate };

    const request$ = this.scheduleId
      ? this.userService.regenerateElectionSchedule(this.scheduleId, payload)
      : this.userService.generateElectionSchedule(payload);

    request$.subscribe({
      next: (res: any) => {
        if (res?.data) this.applyRecord(res.data);
        alert(
          this.scheduleId
            ? 'அட்டவணை மீண்டும் உருவாக்கப்பட்டது (Regenerated)'
            : 'அட்டவணை உருவாக்கப்பட்டது (Generated)'
        );
      },
      error: (err: any) => alert(err?.error?.message || 'Generate failed')
    });
  }

  // Client-side export from whatever's currently loaded.
  download(): void {

    const rows = this.items.map(item => ({
      'Sl. No': item.no,
      'Programme': item.programme,
      'Statutory Requirement': item.statutoryRequirement,
      'Actual Programme': item.actualProgramme || '',
      'Permissible Cutoff Date': item.permissibleCutoffDate || '',
      'Remarks': item.remarks || '',
      'Auto Generated': item.isAutoGenerated ? 'Yes' : 'No',
      'Holiday Adjusted': item.isHolidayAdjusted ? 'Yes' : 'No'
    }));

    const sheet = XLSX.utils.json_to_sheet(rows);
    sheet['!cols'] = [
      { wch: 8 }, { wch: 55 }, { wch: 55 }, { wch: 18 }, { wch: 20 }, { wch: 30 }, { wch: 14 }, { wch: 16 }
    ];

    const workbook = XLSX.utils.book_new();
    XLSX.utils.sheet_add_aoa(sheet, [[`Date of Poll: ${this.pollingDate || '-'}`]], { origin: -1 });
    XLSX.utils.book_append_sheet(workbook, sheet, 'Election Schedule');

    const buffer = XLSX.write(workbook, { bookType: 'xlsx', type: 'array' });

    saveAs(
      new Blob([buffer], { type: 'application/octet-stream' }),
      'Election_Schedule.xlsx'
    );
  }
}
